import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import { PGlite } from '@electric-sql/pglite';

const alice='11111111-1111-4111-8111-111111111111';
const bob='22222222-2222-4222-8222-222222222222';
const admin='33333333-3333-4333-8333-333333333333';
const melodyId='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const notes=JSON.stringify([{midi:60,beats:1},{midi:null,beats:.5},{midi:64,beats:1.5}]);

test('private drafts, review permissions, immutable scheduling and server-dated publication', async () => {
  const db=new PGlite();
  const role=async(id)=>{await db.exec('reset role'); await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify(id?{sub:id,role:'authenticated'}:{role:'anon'})]); await db.exec('set role '+(id?'authenticated':'anon'));};
  const scalar=async(sql,args=[])=>Object.values((await db.query(sql,args)).rows[0])[0];
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      grant usage on schema public,auth to anon,authenticated;
      create function auth.uid() returns uuid language sql stable as $$ select (nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid $$;
      create table public.users(id uuid primary key,username text not null);
      insert into public.users values('${alice}','Alice'),('${bob}','Bob'),('${admin}','Owner');`);
    await db.exec(await readFile(new URL('../../database/migrations/202610310002_brodle_library.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../database/migrations/202610310003_victory_parts.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../database/migrations/202610310004_piano_range.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../database/migrations/202610310005_delete_approved_melodies.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../database/migrations/202611010008_brodle_archive.sql',import.meta.url),'utf8'));
    await db.query('insert into public.brodle_admins values($1)',[admin]);
    assert.equal(await scalar("select extract(epoch from ('2026-03-30'::timestamp at time zone 'Europe/Lisbon') - ('2026-03-29'::timestamp at time zone 'Europe/Lisbon'))::float8 / 3600"),23);
    assert.equal(await scalar("select extract(epoch from ('2026-10-26'::timestamp at time zone 'Europe/Lisbon') - ('2026-10-25'::timestamp at time zone 'Europe/Lisbon'))::float8 / 3600"),25);
    const dates=(await db.query("select (now() at time zone 'Europe/Lisbon')::date::text as today, ((now() at time zone 'Europe/Lisbon')::date+1)::text as tomorrow, ((now() at time zone 'Europe/Lisbon')::date+2)::text as later, ((now() at time zone 'Europe/Lisbon')::date-1)::text as yesterday")).rows[0];
    await role(alice);
    await db.query(`insert into public.brodle_melodies(id,created_by,title,source,hint,bpm,key_signature,time_signature,notes,final_notes) values($1,$2,'First melody','Source','Clue',96,'F','3/4',$3,$3)`,[melodyId,alice,notes]);
    assert.equal(await scalar('select author_username from public.brodle_melodies'),'Alice');
    await assert.rejects(db.query(`insert into public.brodle_melodies(created_by,bpm,key_signature,time_signature) values($1,120,'C','4/4')`,[bob]),{code:'42501'});
    await assert.rejects(db.query(`update public.brodle_melodies set status='approved' where id=$1`,[melodyId]),{code:'42501'});
    await assert.rejects(db.query(`update public.brodle_melodies set notes=$1 where id=$2`,[JSON.stringify([{midi:104,beats:1}]),melodyId]),{code:'23514'});
    await assert.rejects(db.query(`update public.brodle_melodies set notes=$1 where id=$2`,[JSON.stringify([{midi:60}]),melodyId]),{code:'23514'});
    await assert.rejects(db.query(`update public.brodle_melodies set notes=$1 where id=$2`,[JSON.stringify([{midi:60,beats:.7}]),melodyId]),{code:'23514'});
    const boundaries=JSON.stringify([{midi:31,beats:1},{midi:103,beats:1}]);
    const boundaryChord=JSON.stringify([{midi:31,pitches:[31,103],beats:1}]);
    await db.query('update public.brodle_melodies set notes=$1,final_notes=$2,final_bass_notes=$2 where id=$3',[boundaries,boundaryChord,melodyId]);
    assert.deepEqual(await scalar('select notes from public.brodle_melodies'),JSON.parse(boundaries));
    for (const pitch of [30,104]) {
      for (const column of ['notes','final_notes','final_bass_notes']) await assert.rejects(db.query('update public.brodle_melodies set '+column+'=$1 where id=$2',[JSON.stringify([{midi:pitch,beats:1}]),melodyId]),{code:'23514'});
    }
    await db.query('update public.brodle_melodies set notes=$1 where id=$2',[notes,melodyId]);
    const chord=JSON.stringify([{midi:60,pitches:[60,64,67],beats:4}]);
    const bass=JSON.stringify([{midi:36,beats:2},{midi:null,beats:.5},{midi:43,pitches:[43,47,50],beats:1.5}]);
    await db.query('update public.brodle_melodies set final_notes=$1,final_bass_notes=$2,final_clef=$3,final_bass_clef=$4 where id=$5',[chord,bass,'treble','bass',melodyId]);
    await assert.rejects(db.query('update public.brodle_melodies set notes=$1 where id=$2',[chord,melodyId]),{code:'23514'});
    for (const invalid of [[{midi:60,pitches:[60,60],beats:1}],[{midi:60,pitches:[60,104],beats:1}],[{midi:60,pitches:[60],beats:1}],[{midi:null,pitches:[60,64],beats:1}],[{midi:60,pitches:[64,60],beats:1}]]) await assert.rejects(db.query('update public.brodle_melodies set final_notes=$1 where id=$2',[JSON.stringify(invalid),melodyId]),{code:'23514'});
    await assert.rejects(db.query("update public.brodle_melodies set final_clef='invalid' where id=$1",[melodyId]),{code:'23514'});
    await role(bob);
    assert.equal(await scalar('select count(*)::int from public.brodle_melodies'),0);
    assert.equal((await db.query('update public.brodle_melodies set title=$1 where id=$2 returning id',['stolen',melodyId])).rows.length,0);
    await assert.rejects(db.query('select public.submit_brodle_melody($1)',[melodyId]),/brodle_not_editable/);
    await assert.rejects(db.query("select public.review_brodle_melody($1,'approved','')",[melodyId]),/brodle_admin_required/);
    await assert.rejects(db.query('insert into public.brodle_admins values($1)',[bob]),{code:'42501'});
    await role(admin);
    assert.equal(await scalar('select public.is_brodle_admin()'),true);
    assert.equal(await scalar('select count(*)::int from public.brodle_melodies'),0,'admin cannot see someone else’s private draft');
    await role(alice);
    await db.query('select public.submit_brodle_melody($1)',[melodyId]);
    assert.equal((await db.query('update public.brodle_melodies set title=$1 where id=$2 returning id',['changed',melodyId])).rows.length,0,'submitted versions are locked');
    assert.equal((await db.query('delete from public.brodle_melodies where id=$1 returning id',[melodyId])).rows.length,0,'submitted melodies still cannot be deleted');
    await role(admin);
    assert.equal(await scalar('select count(*)::int from public.brodle_melodies'),1);
    await db.query("select public.review_brodle_melody($1,'rejected','Please revise')",[melodyId]);
    await role(alice);
    assert.equal(await scalar('select review_note from public.brodle_melodies'),'Please revise');
    await db.query('update public.brodle_melodies set title=$1 where id=$2',['Revised melody',melodyId]);
    assert.equal(await scalar('select status from public.brodle_melodies'),'draft');
    await db.query('select public.submit_brodle_melody($1)',[melodyId]);
    await role(admin);
    await db.query("select public.review_brodle_melody($1,'approved','Ready')",[melodyId]);
    const scheduled=await scalar('select public.schedule_brodle_melody($1,$2)',[melodyId,dates.tomorrow]);
    await assert.rejects(db.query('select public.schedule_brodle_melody($1,$2)',[melodyId,dates.tomorrow]),/brodle_date_taken/);
    await assert.rejects(db.query('select public.schedule_brodle_melody($1,$2)',[melodyId,dates.yesterday]),/brodle_date_past/);
    await assert.rejects(db.query("update public.brodle_daily_challenges set snapshot='{}' where id=$1",[scheduled]),{code:'42501'});
    await role(alice);
    await role(bob);
    assert.equal((await db.query('delete from public.brodle_melodies where id=$1 returning id',[melodyId])).rows.length,0,'another creator cannot delete approved melodies');
    await role(alice);
    assert.equal(await scalar('select count(*)::int from public.brodle_daily_challenges'),0,'creators cannot inspect the schedule');
    await role(null);
    await assert.rejects(db.query('select * from public.brodle_melodies'),{code:'42501'});
    await assert.rejects(db.query('select * from public.brodle_daily_challenges'),{code:'42501'});
    let daily=await scalar('select public.get_daily_brodle()');
    assert.equal(daily.challenge,null,'future snapshots stay hidden');
    for (const date of [dates.tomorrow, dates.yesterday]) {
      const day = await scalar('select public.get_brodle_day($1)', [date]);
      assert.equal(day.challenge, null, 'future or empty dates never fall back to another puzzle');
      assert.equal(day.previousDate, null);
      assert.equal(day.nextDate, null);
    }
    assert.equal(daily.today,dates.today);
    assert.ok(Date.parse(daily.nextChangeAt)>Date.parse(daily.serverNow));
    await role(admin);
    await db.query('select public.reschedule_brodle_challenge($1,$2)',[scheduled,dates.later]);
    await db.query('select public.cancel_brodle_challenge($1)',[scheduled]);
    const todayId=await scalar('select public.schedule_brodle_melody($1,$2)',[melodyId,dates.today]);
    await assert.rejects(db.query('select public.reschedule_brodle_challenge($1,$2)',[todayId,dates.later]),/brodle_published_locked/);
    await assert.rejects(db.query('select public.cancel_brodle_challenge($1)',[todayId]),/brodle_published_locked/);
    await role(null);
    daily=await scalar('select public.get_daily_brodle()');
    assert.equal(daily.challenge.id,todayId);
    assert.equal(daily.challenge.snapshot.title,'Revised melody');
    assert.deepEqual(daily.challenge.snapshot.melody,JSON.parse(notes));
    assert.deepEqual(daily.challenge.snapshot.finalMelody,JSON.parse(chord));
    assert.deepEqual(daily.challenge.snapshot.finalBass,JSON.parse(bass));
    assert.equal(daily.challenge.snapshot.finalBassClef,'bass');
    assert.equal(daily.previousDate, null);
    assert.equal(daily.nextDate, null, 'scheduled future dates are excluded from navigation');
    // Archive dates have gaps; arrows must use published neighbours, not date +/- 1.
    await db.exec('reset role');
    for (const days of [3, 6]) await db.query(`insert into public.brodle_daily_challenges(play_date,melody_id,scheduled_by,snapshot)
      select play_date-$1::int,melody_id,scheduled_by,snapshot from public.brodle_daily_challenges where id=$2`, [days,todayId]);
    await role(null);
    daily=await scalar('select public.get_daily_brodle()');
    const middle=daily.previousDate;
    const middleDay=await scalar('select public.get_brodle_day($1)',[middle]);
    assert.equal(middleDay.challenge.playDate,middle);
    assert.equal(middleDay.nextDate,dates.today);
    assert.ok(middleDay.previousDate < middle);
    assert.equal((await scalar('select public.get_brodle_day($1)',[middleDay.previousDate])).previousDate,null,'oldest day has no earlier neighbour');
    assert.equal((await scalar('select public.get_brodle_day($1)',[dates.today])).nextDate,null,'latest day has no future neighbour');
    assert.deepEqual((await scalar('select public.get_brodle_day(null)')).challenge,daily.challenge);
    await role(bob);
    assert.equal((await scalar('select public.get_brodle_day($1)',[middle])).challenge.id,middleDay.challenge.id,'archive is also playable when signed in');
    assert.equal(await scalar('select count(*)::int from public.brodle_daily_challenges'),0,'archive RPC does not grant schedule-table access');
    await db.exec('reset role');
    await db.query("update public.brodle_melodies set title='Source edited by database owner' where id=$1",[melodyId]);
    await role(null);
    assert.equal((await scalar('select public.get_daily_brodle()')).challenge.snapshot.title,'Revised melody','scheduled copies are immutable snapshots');
    // Model an empty next day by moving the fixture into yesterday as the DB owner.
    await db.exec('reset role');
    await db.query('update public.brodle_daily_challenges set play_date=$1 where id=$2',[dates.yesterday,todayId]);
    await role(null);
    daily=await scalar('select public.get_daily_brodle()');
    assert.equal(daily.challenge.id,todayId,'a calendar gap retains the same challenge identity');
    assert.equal(daily.challenge.playDate,dates.yesterday);
    await role(admin);
    const own=await scalar(`insert into public.brodle_melodies(title,bpm,key_signature,time_signature,notes) values('Owner melody',120,'C','4/4',$1) returning id`,[notes]);
    await db.query('select public.schedule_brodle_melody($1,$2)',[own,dates.tomorrow]);
    assert.equal(await scalar('select status from public.brodle_melodies where id=$1',[own]),'approved','admins can schedule their own drafts directly');
    // Owners can delete approved sources; published/future snapshots survive.
    await role(alice);
    assert.equal((await db.query('delete from public.brodle_melodies where id=$1 returning id',[melodyId])).rows.length,1);
    await role(null);
    assert.deepEqual((await scalar('select public.get_daily_brodle()')).challenge.snapshot,daily.challenge.snapshot);
    await role(admin);
    assert.equal(await scalar('select melody_id from public.brodle_daily_challenges where id=$1',[todayId]),null);
    const future=await scalar('select id from public.brodle_daily_challenges where melody_id=$1',[own]);
    assert.equal((await db.query('delete from public.brodle_melodies where id=$1 returning id',[own])).rows.length,1);
    assert.equal(await scalar('select melody_id from public.brodle_daily_challenges where id=$1',[future]),null);
    await db.query('select public.reschedule_brodle_challenge($1,$2)',[future,dates.later]);
    await db.query('select public.cancel_brodle_challenge($1)',[future]);
    // Admins can delete another author's approved source, but not their drafts.
    await role(alice);
    const other=await scalar(`insert into public.brodle_melodies(title,bpm,key_signature,time_signature,notes) values('Delete approved',120,'C','4/4',$1) returning id`,[notes]);
    await role(admin);
    assert.equal((await db.query('delete from public.brodle_melodies where id=$1 returning id',[other])).rows.length,0);
    await role(alice);
    await db.query('select public.submit_brodle_melody($1)',[other]);
    await role(admin);
    assert.equal((await db.query('delete from public.brodle_melodies where id=$1 returning id',[other])).rows.length,0);
    await db.query("select public.review_brodle_melody($1,'approved','')",[other]);
    assert.equal((await db.query('delete from public.brodle_melodies where id=$1 returning id',[other])).rows.length,1);

  } finally { await db.close(); }
});
